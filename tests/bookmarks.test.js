const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { JSDOM, VirtualConsole } = require('jsdom');
const fixture = require('./bookmark-sync.test');
const ROOT = path.resolve(__dirname, '..');
const tick = () => new Promise(resolve => setTimeout(resolve, 20));
(async () => {
  for (const language of ['zh-CN', 'en']) {
    const f = fixture({ laterOnSettings: { language } });
    const errors = [];
    const vc = new VirtualConsole();
    vc.on('jsdomError', error => errors.push(error.message));
    const dom = new JSDOM(fs.readFileSync(path.join(ROOT, 'bookmarks.html'), 'utf8'), { runScripts: 'outside-only', url: 'chrome-extension://fixture/bookmarks.html?items=%5B%22reading%22%5D', virtualConsole: vc });
    const { window } = dom;
    const calls = [];
    window.chrome = f.chrome;
    let allowPermission = false;
    window.chrome.permissions.request = async () => { calls.push('permission'); if (!allowPermission) return false; f.grant(); return true; };
    window.chrome.runtime.sendMessage = async message => {
      calls.push(message);
      try { return { ok: true, state: await f.api.handle(message) }; }
      catch (error) { return { ok: false, error: error.message }; }
    };
    let confirm = false;
    window.LaterOnDialog = { async confirm() { return confirm; }, async prompt() { return { ok: false }; }, async alert() {} };
    window.eval(fs.readFileSync(path.join(ROOT, 'i18n.js'), 'utf8'));
    try {
      window.eval(fs.readFileSync(path.join(ROOT, 'bookmark-view.js'), 'utf8'));
      window.eval(fs.readFileSync(path.join(ROOT, 'bookmarks.js'), 'utf8'));
      await tick();
      const $ = selector => window.document.querySelector(selector);
      assert.equal($('#bookmarkEnable').hidden, false);
      assert.equal($('#bookmarkAddPanel').hidden, true);
      assert.equal($('#bookmarkTransfer').hidden, false);
      assert.equal($('#bookmarkCopy').disabled, true);
      $('#bookmarkEnable').click();
      await tick();
      assert.equal($('#bookmarkEnable').hidden, false, 'Declined permission does not enable sync');
      assert.equal($('#bookmarkCopy').disabled, true);
      assert.equal(f.store.laterOnBookmarkConfig?.enabled, undefined);
      allowPermission = true;
      $('#bookmarkEnable').click();
      await tick();
      assert(calls.includes('permission'));
      assert.equal($('#bookmarkEnable').hidden, true);
      assert.equal($('#bookmarkScope').value, '');
      assert.equal($('#bookmarkAddPanel').hidden, false);
      assert.equal($('#bookmarkList').querySelectorAll('.bookmark-row').length, 3);
      await f.chrome.bookmarks.create({ parentId: '2', title: 'Browser event', url: 'https://event.test/' });
      await tick();
      assert($('#bookmarkList').textContent.includes('Browser event'), 'Browser changes appear in the page without manual refresh');
      $('#bookmarkSearch').value = 'outside';
      $('#bookmarkSearch').dispatchEvent(new window.Event('input'));
      assert.equal($('#bookmarkList').querySelectorAll('.bookmark-row').length, 1);
      $('#bookmarkSearch').value = '';
      $('#bookmarkSearch').dispatchEvent(new window.Event('input'));
      $('#bookmarkTitle').value = '<img src=x onerror=alert(1)>';
      $('#bookmarkUrl').value = 'https://ui.test/page';
      $('#bookmarkParent').value = 'scope';
      $('#bookmarkAddForm').dispatchEvent(new window.Event('submit', { bubbles: true, cancelable: true }));
      await tick();
      const native = f.nodes.find(node => node.url === 'https://ui.test/page');
      assert(native);
      assert.equal($('#bookmarkList').querySelectorAll('img[src="x"]').length, 0, 'Bookmark titles must not be interpreted as HTML');
      let row = [...$('#bookmarkList').children].find(el => el.dataset.id === native.id);
      row.querySelector('[data-action="move"]').click();
      assert.equal($('#bookmarkMoveForm').hidden, false);
      $('#bookmarkMoveFolder').value = 'nested';
      $('#bookmarkMoveForm').dispatchEvent(new window.Event('submit', { bubbles: true, cancelable: true }));
      await tick();
      assert.equal(f.nodes.find(node => node.id === native.id).parentId, 'nested');
      assert.equal($('#bookmarkMoveForm').hidden, true);
      window.LaterOnDialog.prompt = async () => ({ ok: true, values: { title: 'Edited bookmark', url: 'https://ui.test/edited' } });
      row = [...$('#bookmarkList').children].find(el => el.dataset.id === native.id);
      row.querySelector('[data-action="edit"]').click();
      await tick();
      assert.equal(f.nodes.find(node => node.id === native.id).title, 'Edited bookmark');
      assert.equal(f.nodes.find(node => node.id === native.id).url, 'https://ui.test/edited');
      row = [...$('#bookmarkList').children].find(el => el.dataset.id === native.id);
      row.querySelector('[data-action="remove"]').click();
      await tick();
      assert(f.nodes.some(node => node.id === native.id), 'Canceling preserves native bookmarks');
      confirm = true;
      row.querySelector('[data-action="remove"]').click();
      await tick();
      assert(!f.nodes.some(node => node.id === native.id));
      $('#bookmarkScope').value = 'scope';
      $('#bookmarkScope').dispatchEvent(new window.Event('change'));
      $('#bookmarkApplyScope').click();
      await tick();
      assert(!$('#bookmarkList').textContent.includes('Outside'));
      assert.equal(f.store.laterOnBookmarkConfig.scopeId, 'scope');
      $('#bookmarkTransferFolder').value = 'nested';
      $('#bookmarkTransferFolder').dispatchEvent(new window.Event('change'));
      await f.chrome.bookmarks.move('nested', { parentId: '2' });
      await tick();
      assert.equal($('#bookmarkTransferFolder').value, 'nested', 'A disappearing destination is not replaced by a different folder');
      assert.equal($('#bookmarkCopy').disabled, true);
      await f.chrome.bookmarks.move('nested', { parentId: 'scope' });
      await tick();
      $('#bookmarkCopy').click();
      await tick();
      assert(f.nodes.some(node => node.parentId === 'nested' && node.url === 'https://example.com/paper'));
      assert.equal(f.store.laterOnItems.length, 1);
      assert.equal($('#bookmarkCopy').disabled, true, 'Completed transfers cannot be resubmitted');
      const count = f.nodes.length;
      $('#bookmarkDisable').click();
      await tick();
      assert.equal(f.nodes.length, count);
      assert.equal($('#bookmarkAddPanel').hidden, true);
      assert.equal(errors.length, 0, errors.join('\n'));
    } finally { dom.window.close(); }
  }
  console.log('PASS bookmark UI: opt-in permission, scoped native changes, safe titles, confirmation, transfer isolation, disabled controls and both languages');
})().catch(error => { console.error(error); process.exitCode = 1; });
