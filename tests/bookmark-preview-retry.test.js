const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { JSDOM } = require('jsdom');
const fixture = require('./bookmark-sync.test');
const tick = () => new Promise(resolve => setTimeout(resolve, 10));
const until = async check => { for (let i = 0; i < 100 && !check(); i++) await tick(); assert(check()); };
(async () => {
  const f = fixture({ laterOnBookmarkConfig: { enabled: true, scopeId: 'scope' }, laterOnItems: [] });
  f.grant();
  let requests = 0, active = false, priorities = 0;
  f.ctx.fetch = async () => { requests++; throw Error('Not available yet'); };
  const read = name => fs.readFileSync(path.resolve(__dirname, '..', name), 'utf8');
  const dom = new JSDOM(read('bookmarks.html'), { runScripts: 'outside-only', url: 'chrome-extension://fixture/bookmarks.html' });
  try {
    dom.window.chrome = f.chrome;
    dom.window.LaterOnSidepanelSwitch = { isActive: () => active, ready() {} };
    f.chrome.runtime.sendMessage = async message => {
      if (message.type === 'BOOKMARKS_PREVIEWS') priorities++;
      return { ok: true, state: await f.api.handle(message) };
    };
    for (const name of ['i18n.js', 'bookmark-view.js', 'bookmarks.js']) dom.window.eval(read(name));
    await until(() => dom.window.document.querySelectorAll('.bookmark-card').length === 1);
    await tick(); await tick();
    assert.equal(priorities, 0, 'A mounted hidden surface does not reprioritize visible pins');
    assert.equal(requests, 0);
    active = true;
    dom.window.dispatchEvent(new dom.window.Event('lateron-sidepanel-visible'));
    await until(() => f.store.laterOnBookmarkPreviews?.inside?.attemptedAt);
    assert.equal(dom.window.document.querySelector('#bookmarkLoadPreviews'), null);
    assert.equal(requests, 1, 'Missing previews load automatically');
    await tick();
    const beforeHidden = priorities;
    active = false;
    const search = dom.window.document.querySelector('#bookmarkSearch');
    search.value = 'no matches'; search.dispatchEvent(new dom.window.Event('input'));
    search.value = ''; search.dispatchEvent(new dom.window.Event('input'));
    await tick();
    assert.equal(priorities, beforeHidden, 'Hidden retained views cannot take back queue priority during redraws');
    active = true;
    dom.window.dispatchEvent(new dom.window.Event('lateron-sidepanel-visible'));
    await f.api.handle({ type: 'BOOKMARKS_GET' });
    dom.window.document.querySelector('#bookmarkSearch').dispatchEvent(new dom.window.Event('input'));
    await tick(); await tick();
    assert.equal(requests, 1, 'Re-rendering and refreshing cannot hammer unavailable sites');
    f.store.laterOnBookmarkPreviewQueue.attempted.inside.at -= 25 * 60 * 60 * 1000;
    f.store.laterOnBookmarkPreviews.inside.attemptedAt -= 25 * 60 * 60 * 1000;
    await f.api.handle({ type: 'BOOKMARKS_GET' });
    await until(() => requests === 2);
    await until(() => f.store.laterOnBookmarkPreviewQueue.pending.length === 0);
    assert.equal(requests, 2, 'Unavailable previews become eligible again after the retry cooldown');
  } finally { dom.window.close(); }
  console.log('PASS bookmark preview retry: automatic loading, no manual control, redraw deduplication and persistent cooldown');
})().catch(error => { console.error(error); process.exitCode = 1; });
